//! The `com.nilfactor.Clippo` D-Bus surface, defined exactly once.
//!
//! Three binaries speak this interface — `clippod` serves it, `clippo` and
//! `clippo-applet` call it — and D-Bus checks signatures at *runtime*. A
//! parameter that drifts from `u` to `x` in one crate and not the others is an
//! `org.freedesktop.DBus.Error.InvalidArgs` at the moment a user clicks
//! something, with nothing at compile time to warn anybody. So neither side
//! restates the signatures:
//!
//! - [`ClippoInterface`] is the served side, `#[zbus::interface]` and all. It
//!   holds no state of its own; it forwards to a [`ClippoBackend`], which is
//!   the trait `clippod` implements.
//! - [`ClippoProxy`] is the calling side, generated by `#[zbus::proxy]` from
//!   the same member list.
//!
//! Changing a signature therefore means changing it here, and every crate that
//! disagrees stops compiling.
//!
//! # The members
//!
//! DESIGN.md's table, verbatim — see `clippod` there:
//!
//! | Member | Signature |
//! |---|---|
//! | `List` | `(limit, offset) -> Vec<EntrySummary>` |
//! | `Search` | `(query, limit) -> Vec<EntrySummary>` |
//! | `Copy` / `Delete` | `(id)` |
//! | `Pin` | `(id, bool)` |
//! | `Clear` | `(include_pinned)` |
//! | `Reveal` | `(id) -> String` |
//! | `Thumbnail` | `(id) -> Vec<u8>` |
//! | `SetPaused` / `Paused` | `(bool)` / `-> bool` |
//! | `HistoryChanged` | signal |
//!
//! `Thumbnail` is the one member DESIGN.md's table does not list, added at M5.
//! Its absence was a gap rather than a decision: the design has capture derive
//! and store a thumbnail expressly "so the applet never decodes full-size
//! images", and without a member to fetch one the applet could only have got
//! there through the full-size blob — the thing the thumbnail exists to avoid.
//! It returns derived bytes, not stored content, so it does not widen what
//! [`Reveal`][ClippoBackend::reveal] is the sole route for.
//!
//! # The other direction
//!
//! [`AppletInterface`] and [`ClippoAppletProxy`] are a second, much smaller
//! interface that the *applet* serves and `clippo show` calls. See
//! [`applet`](crate::applet) for why it is a separate bus name.
//!
//! # Previews and full values
//!
//! [`EntrySummary::preview`] is the *only* content [`List`][ClippoBackend::list]
//! and [`Search`][ClippoBackend::search] return, and
//! [`Reveal`][ClippoBackend::reveal] is the only member that returns a whole
//! stored value. That split is load bearing: M4 makes previews of suspected
//! secrets masked, and it does so by changing the one function that builds a
//! preview. If a full value could leave by any other route, M4 would be a
//! redesign instead of an edit.
//!
//! ```no_run
//! # async fn example() -> Result<(), Box<dyn std::error::Error>> {
//! let connection = zbus::Connection::session().await?;
//! let clippo = clippo_ipc::ClippoProxy::new(&connection).await?;
//! for entry in clippo.list(10, 0).await? {
//!     println!("{}\t{}", entry.id, entry.preview);
//! }
//! # Ok(())
//! # }
//! ```

